// nlcl_channels.hpp - NLCL channel transports (C++17, no third-party deps).
//
//   local   : both ends in this process, delivered in memory
//   http    : POST/GET flat JSON on the NLCL hub (python module) via a tiny
//             raw-socket HTTP/1.1 client      (also used for "websocket")
//   udp     : one JSON datagram per message (Winsock2 / BSD sockets)
//   serial  : newline-terminated JSON on stdout; incoming lines on stdin
//             (pipe it through a serial bridge, see README)  (also spi/i2c/gpio/wire)
//   mqtt    : minimal MQTT 3.1.1 client, QoS 0 publish/subscribe
//
// Every transport falls back gracefully (prints the payload) when the network
// is unavailable; run with --simulate to invent incoming data instead.
// Only nlcl_channels.cpp includes this file, so OS headers (windows.h macros)
// never reach entity code.  Generated by NLCL - edit freely.
