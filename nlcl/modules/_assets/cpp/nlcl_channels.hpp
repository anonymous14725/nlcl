// One-time socket library initialisation.
inline void init() {
#ifdef _WIN32
    struct WsaInit {
        bool ok = false;
        WsaInit() {
            WSADATA d;
            ok = WSAStartup(MAKEWORD(2, 2), &d) == 0;
        }
        ~WsaInit() {
            if (ok) WSACleanup();
        }
    };
    static WsaInit once;
#else
    static bool once = [] {
        std::signal(SIGPIPE, SIG_IGN);  // a closed peer must not kill the process
        return true;
    }();
    (void)once;
#endif
}

inline void setNonBlocking(socket_t s, bool on) {
#ifdef _WIN32
    u_long mode = on ? 1 : 0;
    ioctlsocket(s, FIONBIO, &mode);
#else
    int fl = fcntl(s, F_GETFL, 0);
    if (fl < 0) fl = 0;
    fcntl(s, F_SETFL, on ? (fl | O_NONBLOCK) : (fl & ~O_NONBLOCK));
#endif
}

inline void setTimeouts(socket_t s, int ms) {
#ifdef _WIN32
    DWORD t = static_cast<DWORD>(ms);
    setsockopt(s, SOL_SOCKET, SO_RCVTIMEO, reinterpret_cast<const char*>(&t), sizeof(t));
    setsockopt(s, SOL_SOCKET, SO_SNDTIMEO, reinterpret_cast<const char*>(&t), sizeof(t));
#else
    timeval tv;
    tv.tv_sec = ms / 1000;
    tv.tv_usec = (ms % 1000) * 1000;
    setsockopt(s, SOL_SOCKET, SO_RCVTIMEO, &tv, sizeof(tv));
    setsockopt(s, SOL_SOCKET, SO_SNDTIMEO, &tv, sizeof(tv));
#endif
}

// IPv4 address for host ("localhost" is mapped to 127.0.0.1 to avoid IPv6 delays).
inline bool resolve(const std::string& host, int port, sockaddr_in& out) {
    init();
    std::string h = (host.empty() || host == "localhost") ? "127.0.0.1" : host;
    addrinfo hints{};
    hints.ai_family = AF_INET;
    addrinfo* res = nullptr;
    if (getaddrinfo(h.c_str(), nullptr, &hints, &res) != 0 || !res) return false;
    out = *reinterpret_cast<sockaddr_in*>(res->ai_addr);
    out.sin_port = htons(static_cast<unsigned short>(port));
    freeaddrinfo(res);
    return true;
}

// TCP connect with a timeout (non-blocking connect + select).
inline socket_t tcpConnect(const std::string& host, int port, int timeoutMs) {
    sockaddr_in addr{};
    if (!resolve(host, port, addr)) return kInvalid;
    socket_t s = socket(AF_INET, SOCK_STREAM, IPPROTO_TCP);
    if (s == kInvalid) return kInvalid;
    setNonBlocking(s, true);
    int rc = connect(s, reinterpret_cast<sockaddr*>(&addr), static_cast<int>(sizeof(addr)));
    if (rc != 0) {
        fd_set wf, ef;
        FD_ZERO(&wf);
        FD_ZERO(&ef);
        FD_SET(s, &wf);
        FD_SET(s, &ef);
        timeval tv;
        tv.tv_sec = timeoutMs / 1000;
        tv.tv_usec = (timeoutMs % 1000) * 1000;
        int n = select(static_cast<int>(s) + 1, nullptr, &wf, &ef, &tv);
        int err = 0;
        socklen_t len = static_cast<socklen_t>(sizeof(err));
        if (n <= 0 || FD_ISSET(s, &ef) ||
            getsockopt(s, SOL_SOCKET, SO_ERROR, reinterpret_cast<char*>(&err), &len) != 0 || err != 0) {
            closeSocket(s);
            return kInvalid;
        }
    }
    setNonBlocking(s, false);
    setTimeouts(s, timeoutMs);
    return s;
}

inline bool sendAll(socket_t s, const std::string& data) {
    size_t off = 0;
    while (off < data.size()) {
        int n = static_cast<int>(send(s, data.data() + off, static_cast<int>(data.size() - off), kSendFlags));
        if (n <= 0) return false;
        off += static_cast<size_t>(n);
    }
    return true;
}

// Minimal HTTP/1.1 request (Connection: close). Returns status code or -1.
inline int httpRequest(const std::string& host, int port, const std::string& method, const std::string& path,
                       const std::string& body, std::string& out, int timeoutMs = 400) {
    socket_t s = tcpConnect(host, port, timeoutMs);
    if (s == kInvalid) return -1;
    std::string req = method + " " + path + " HTTP/1.1\r\nHost: " + host + ":" + std::to_string(port) +
                      "\r\nConnection: close\r\nAccept: application/json\r\n";
    if (method == "POST")
        req += "Content-Type: application/json\r\nContent-Length: " + std::to_string(body.size()) + "\r\n";
    req += "\r\n" + body;
    if (!sendAll(s, req)) {
        closeSocket(s);
        return -1;
    }
    std::string resp;
    char buf[2048];
    while (resp.size() < (1u << 20)) {
        int n = static_cast<int>(recv(s, buf, static_cast<int>(sizeof(buf)), 0));
        if (n <= 0) break;
        resp.append(buf, static_cast<size_t>(n));
        // stop early once the announced body is complete
        size_t he = resp.find("\r\n\r\n");
        if (he != std::string::npos) {
            size_t cl = resp.find("Content-Length:");
            if (cl == std::string::npos) cl = resp.find("content-length:");
            if (cl != std::string::npos && cl < he) {
                size_t want = static_cast<size_t>(std::strtoul(resp.c_str() + cl + 15, nullptr, 10));
                if (resp.size() >= he + 4 + want) break;
            }
        }
    }
    closeSocket(s);
    size_t he = resp.find("\r\n\r\n");
    if (resp.compare(0, 5, "HTTP/") != 0 || he == std::string::npos) return -1;
    size_t sp = resp.find(' ');
    int status = std::atoi(resp.c_str() + sp + 1);
    out = resp.substr(he + 4);
    return status;
}

// "http://localhost:8765/x" -> host, port
inline void parseUrl(const std::string& url, std::string& host, int& port) {
    std::string u = url;
    size_t p = u.find("://");
    if (p != std::string::npos) u = u.substr(p + 3);
    size_t slash = u.find('/');
    if (slash != std::string::npos) u = u.substr(0, slash);
    size_t colon = u.rfind(':');
    if (colon != std::string::npos) {
        host = u.substr(0, colon);
        port = std::atoi(u.c_str() + colon + 1);
    } else {
        host = u;
    }
    if (host.empty()) host = "127.0.0.1";
    if (port <= 0) port = 80;
}

