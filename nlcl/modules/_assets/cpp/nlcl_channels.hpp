// ------------------------------------------------------------------ mqtt (3.1.1, QoS 0)
class MqttChannel : public ChannelBase {
public:
    std::string broker = "broker.hivemq.com";
    int brokerPort = 1883;
    std::string topic;

    void start() override {
        broker = cfgStr(config, "broker", broker);
        brokerPort = cfgInt(config, "broker_port", brokerPort);
        topic = cfgStr(config, "topic", "nlcl/" + id);
        if (world->simulate) return;
        sock_ = net::tcpConnect(broker, brokerPort, 3000);
        if (sock_ == net::kInvalid) {
            std::cerr << "[" << id << "] mqtt broker " << broker << " unreachable - printing messages instead" << std::endl;
            return;
        }
        std::string body;
        putStr(body, "MQTT");
        body += static_cast<char>(4);     // protocol level 3.1.1
        body += static_cast<char>(0x02);  // clean session
        body += static_cast<char>(0);
        body += static_cast<char>(60);    // keep-alive 60 s
        putStr(body, "nlcl-" + id + "-" + std::to_string(world->rng() % 1000000u));
        unsigned char ack[4] = {0, 0, 0, 0};
        size_t got = 0;
        if (net::sendAll(sock_, packet(0x10, body))) {
            while (got < 4) {
                int n = static_cast<int>(recv(sock_, reinterpret_cast<char*>(ack) + got, static_cast<int>(4 - got), 0));
                if (n <= 0) break;
                got += static_cast<size_t>(n);
            }
        }
        if (got < 4 || ack[0] != 0x20 || ack[3] != 0) {
            std::cerr << "[" << id << "] mqtt connect refused - printing messages instead" << std::endl;
            close();
            return;
        }
        if (!localSrc) {  // SUBSCRIBE packet id 1, QoS 0
            std::string sb;
            sb += static_cast<char>(0);
            sb += static_cast<char>(1);
            putStr(sb, topic);
            sb += static_cast<char>(0);
            net::sendAll(sock_, packet(0x82, sb));
        }
        net::setNonBlocking(sock_, true);
        pingAt_ = world->now + 30.0;
        if (world->verbose) std::cout << "[" << id << "] mqtt " << broker << ":" << brokerPort << " topic " << topic << std::endl;
    }
    void publish(const Fields& p) override {
        std::string msg = envelope(p);
        if (sock_ != net::kInvalid) {
            std::string body;
            putStr(body, topic);
            body += msg;
            if (!net::sendAll(sock_, packet(0x30, body))) close();
            pingAt_ = world->now + 30.0;
        }
        if (world->verbose) std::cout << "[" << id << "] (mqtt " << topic << ") " << msg << std::endl;
    }
    void poll() override {
        if (sock_ == net::kInvalid) return;
        char buf[2048];
        for (int i = 0; i < 16; ++i) {
            int n = static_cast<int>(recv(sock_, buf, static_cast<int>(sizeof(buf)), 0));
            if (n == 0) {  // broker closed the connection
                close();
                return;
            }
            if (n < 0) break;  // would block: nothing more right now
            rx_.append(buf, static_cast<size_t>(n));
        }
        parse();
        if (world->now >= pingAt_ && sock_ != net::kInvalid) {
            pingAt_ = world->now + 30.0;
            net::sendAll(sock_, std::string("\xC0\x00", 2));
        }
    }
    void stop() override {
        if (sock_ != net::kInvalid) net::sendAll(sock_, std::string("\xE0\x00", 2));  // DISCONNECT
        close();
    }

private:
    net::socket_t sock_ = net::kInvalid;
    std::string rx_;
    double pingAt_ = 0.0;

    void close() {
        if (sock_ != net::kInvalid) net::closeSocket(sock_);
        sock_ = net::kInvalid;
    }
    static void putStr(std::string& b, const std::string& s) {
        b += static_cast<char>((s.size() >> 8) & 0xFF);
        b += static_cast<char>(s.size() & 0xFF);
        b += s;
    }
    static std::string packet(unsigned char type, const std::string& body) {
        std::string p(1, static_cast<char>(type));
        size_t len = body.size();
        do {
            unsigned char d = static_cast<unsigned char>(len % 128);
            len /= 128;
            if (len) d |= 0x80;
            p += static_cast<char>(d);
        } while (len);
        return p + body;
    }
    // split rx_ into complete MQTT packets; deliver PUBLISH payloads
    void parse() {
        while (rx_.size() >= 2) {
            size_t len = 0, mult = 1, pos = 1;
            bool complete = false;
            while (pos < rx_.size() && pos <= 4) {
                unsigned char d = static_cast<unsigned char>(rx_[pos++]);
                len += (d & 0x7F) * mult;
                mult *= 128;
                if (!(d & 0x80)) {
                    complete = true;
                    break;
                }
            }
            if (!complete || rx_.size() < pos + len) return;  // wait for more bytes
            unsigned char type = static_cast<unsigned char>(rx_[0]);
            std::string body = rx_.substr(pos, len);
            rx_.erase(0, pos + len);
            if ((type >> 4) != 3 || body.size() < 2) continue;  // only PUBLISH carries data
            size_t tlen = (static_cast<unsigned char>(body[0]) << 8) | static_cast<unsigned char>(body[1]);
            size_t off = 2 + tlen + (((type >> 1) & 3) ? 2 : 0);
            if (off > body.size()) continue;
            Fields msg;
            if (decodeJson(body.substr(off), msg)) receive(cleanPayload(msg));
        }
    }
};

