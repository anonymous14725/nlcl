// ------------------------------------------------------------------ http hub
class HubChannel : public ChannelBase {
public:
    std::string host = "127.0.0.1";
    int port = 8765;
    std::string path;

    void start() override {
        net::parseUrl(cfgStr(config, "hub_url", "http://localhost:8765"), host, port);
        path = cfgStr(config, "path", "/channel/" + id);
        if (world->verbose)
            std::cout << "[" << id << "] http hub " << host << ":" << port << path << std::endl;
    }
    void publish(const Fields& p) override {
        std::string body = envelope(p), resp;
        if (world->now < retryAt_) {  // hub was down a moment ago: do not stall the loop
            if (world->verbose) std::cout << "[" << id << "] (hub offline) " << body << std::endl;
            return;
        }
        int st = net::httpRequest(host, port, "POST", path, body, resp);
        if (st == 200) {
            if (world->verbose) std::cout << "[" << id << "] -> hub " << body << std::endl;
        } else {
            offline();
            if (world->verbose) std::cout << "[" << id << "] hub unreachable; payload " << body << std::endl;
        }
    }
    void poll() override {
        if (world->now < nextPoll_ || world->now < retryAt_) return;
        nextPoll_ = world->now + std::max(0.2, interval / 2.0);
        std::string resp;
        if (net::httpRequest(host, port, "GET", path, "", resp) != 200) {
            offline();
            return;
        }
        Fields msg;
        if (!decodeJson(resp, msg) || msg.empty()) return;
        auto t = msg.find("_t");
        double stamp = t != msg.end() ? t->second.asNum() : -1.0;
        if (t == msg.end() || stamp == seen_) return;  // nothing new
        seen_ = stamp;
        receive(cleanPayload(msg));
    }

private:
    double nextPoll_ = 0.0, retryAt_ = 0.0, seen_ = -1.0;
    bool warned_ = false;
    void offline() {
        retryAt_ = world->now + 3.0;
        if (!warned_) {
            warned_ = true;
            std::cerr << "[" << id << "] NLCL hub not reachable at " << host << ":" << port
                      << " - start it with: python ../python/main.py   (or run this program with --simulate)"
                      << std::endl;
        }
    }
};

// ------------------------------------------------------------------ udp
class UdpChannel : public ChannelBase {
public:
    std::string host = "127.0.0.1";
    int port = 9876;

    void start() override {
        host = cfgStr(config, "host", "127.0.0.1");
        port = cfgInt(config, "port", 9876);
        if (world->simulate) return;
        net::init();
        sock_ = socket(AF_INET, SOCK_DGRAM, IPPROTO_UDP);
        if (sock_ == net::kInvalid) {
            std::cerr << "[" << id << "] cannot create udp socket" << std::endl;
            return;
        }
        if (!localSrc) {
            sockaddr_in a{};
            a.sin_family = AF_INET;
            a.sin_port = htons(static_cast<unsigned short>(port));
            a.sin_addr.s_addr = htonl(INADDR_ANY);
            if (bind(sock_, reinterpret_cast<sockaddr*>(&a), static_cast<int>(sizeof(a))) != 0) {
                std::cerr << "[" << id << "] udp port " << port << " busy" << std::endl;
                net::closeSocket(sock_);
                sock_ = net::kInvalid;
                return;
            }
            net::setNonBlocking(sock_, true);
        } else if (!net::resolve(host, port, to_)) {
            std::cerr << "[" << id << "] cannot resolve " << host << std::endl;
        }
        if (world->verbose) std::cout << "[" << id << "] udp " << host << ":" << port << std::endl;
    }
    void poll() override {
        if (sock_ == net::kInvalid) return;
        char buf[4096];
        for (int i = 0; i < 64; ++i) {  // drain what is queued, never block
            int n = static_cast<int>(recvfrom(sock_, buf, static_cast<int>(sizeof(buf)), 0, nullptr, nullptr));
            if (n <= 0) break;
            Fields msg;
            if (!decodeJson(std::string(buf, static_cast<size_t>(n)), msg)) continue;
            auto c = msg.find("channel");
            if (c == msg.end() || c->second.asStr() == id) receive(cleanPayload(msg));
        }
    }
    void publish(const Fields& p) override {
        std::string line = envelope(p) + "\n";
        if (sock_ != net::kInvalid && to_.sin_family == AF_INET) {
            sendto(sock_, line.c_str(), static_cast<int>(line.size()), 0, reinterpret_cast<sockaddr*>(&to_),
                   static_cast<int>(sizeof(to_)));
        }
        if (world->verbose) std::cout << "[" << id << "] (udp " << host << ":" << port << ") " << envelope(p) << std::endl;
    }
    void stop() override {
        if (sock_ != net::kInvalid) net::closeSocket(sock_);
        sock_ = net::kInvalid;
    }

private:
    net::socket_t sock_ = net::kInvalid;
    sockaddr_in to_{};
};

