inline std::string cfgStr(const Fields& c, const std::string& k, const std::string& def) {
    auto it = c.find(k);
    return it != c.end() && !it->second.isNull() ? it->second.asStr() : def;
}
inline int cfgInt(const Fields& c, const std::string& k, int def) {
    auto it = c.find(k);
    return it != c.end() && !it->second.isNull() ? static_cast<int>(it->second.asNum()) : def;
}

