"""NLCL Python runtime (stdlib only; pyserial / paho-mqtt used if installed).

Provides: Entity base class, World scheduler (ticks, timers, change detection),
transports for cross-module channels (local, HTTP hub, serial, MQTT, UDP) and
a tiny HTTP hub with a live dashboard page.  Generated by NLCL.
"""
from __future__ import annotations

import json
import os
