def main_args(argv=None):
    import argparse
    p = argparse.ArgumentParser()
    p.add_argument("--seconds", type=float, default=None, help="stop after N seconds")
    p.add_argument("--ticks", type=int, default=None, help="stop after N ticks")
    p.add_argument("--simulate", action="store_true", help="no hardware/network: fake remote data")
    p.add_argument("--no-hub", action="store_true", help="do not start the HTTP hub in-process")
    p.add_argument("--quiet", action="store_true")
    return p.parse_args(argv)
