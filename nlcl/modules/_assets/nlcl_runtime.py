# ---------------------------------------------------------------- entities
class Entity:
    kind = "object"
    props: tuple = ()
    aliases: dict = {}           # property name -> python attribute (when it clashes with a method)

    def __init__(self, world, name):
        self.world = world
        self.name = name
        self.alive = True
        self._timers = []        # [interval_ms, next_due, fn]
        self._last = {}
        self._edges = {}
        self._mirrored = set()    # fields received from other entities

    def _attr(self, prop):
        return self.aliases.get(prop, prop)

    def get(self, prop, default=None):
        return getattr(self, self._attr(prop), default)

    def changed(self, key, value):
        """True when a watched value (e.g. another entity's property) differs from last tick."""
        prev = self._edges.get(("chg", key), value)
        self._edges[("chg", key)] = value
        return value != prev

    def rising(self, key, value):
        """True only when `value` turns true (edge-triggered "when ..." behaviours)."""
        prev = self._edges.get(key, False)
        self._edges[key] = bool(value)
        return bool(value) and not prev

    def every(self, ms, fn):
        self._timers.append([ms, time.monotonic() + ms / 1000.0, fn])

    def state(self):
        return {p: getattr(self, self._attr(p), None) for p in self.props}

    def _watch(self):
        """Values watched for "when <prop> changes": own properties + mirrored remote fields."""
        cur = self.state()
        for k in self._mirrored:
            cur.setdefault(k, self.get(k))
        return cur

    def log(self, text):
        def sub(m):
            key = m.group(1)
            v = self.get(key)
            if v is None or callable(v):
                v = self.world.latest(key)
            return m.group(0) if v is None else str(v)
        print(f"[{self.name}] " + re.sub(r"\{(\w+)\}", sub, str(text)), flush=True)

    def destroy(self):
        self.alive = False
        self.world.destroy(self)

    def move(self, dx, dy, dz):
        pos = list(getattr(self, "position", [0, 0, 0]) or [0, 0, 0])
        pos = (pos + [0, 0, 0])[:3]
        self.position = [pos[0] + dx, pos[1] + dy, pos[2] + dz]

    def send(self, to=None, fields=None):
        self.world.send(self, to, fields)

    def rotation(self):
        """Orientation in degrees [x, y, z]: angle_x / angle_y / angle (rotation about z)."""
        return [float(getattr(self, self._attr(p), 0) or 0) % 360 for p in ("angle_x", "angle_y", "angle")]

    # hooks overridden by generated code
    def on_start(self): pass
    def on_update(self, dt): pass
    def on_change(self, prop): pass
    def on_message(self, sender, msg): pass
    def on_collision(self, other): pass
    def on_input(self, key): pass


# ---------------------------------------------------------------- world
class World:
    def __init__(self, simulate=False, verbose=True):
        self.entities = {}
        self.channels = []
        self.remote = {}         # (entity, field) -> last value from another module
        self._latest = {}        # field -> last value from any module
        self.simulate = simulate
        self.verbose = verbose
        self.running = False
        self._lock = threading.RLock()   # re-entrant: behaviours may send() while the loop holds it

    def add(self, e):
        self.entities[e.name] = e
        return e

    def __getitem__(self, name):
        return self.entities[name]

    def get_remote(self, entity, field, default=0):
        e = self.entities.get(entity)
        if e is not None and hasattr(e, e._attr(field)):
            return e.get(field)
        if (entity, field) in self.remote:
            return self.remote[(entity, field)]
        # data often arrives via the parent board's link (node.temperature for sensor temp)
        return self._latest.get(field, default)

    def set_remote(self, entity, field, value):
        """Assign a property of another entity (local object, else the cached remote value)."""
        e = self.entities.get(entity)
        if e is not None:
            setattr(e, e._attr(field), value)
        else:
            self.remote[(entity, field)] = value

    def latest(self, field):
        """Most recent value of `field` received from any other module (or None)."""
        return self._latest.get(field)

    def collide(self, a, b):
        """Report a contact between two entities (no physics here: call it from your own code
        or a channel handler).  Both sides' on_collision run; each filters by name/kind."""
        a = self.entities.get(a, a) if isinstance(a, str) else a
        b = self.entities.get(b, b) if isinstance(b, str) else b
        if isinstance(a, str) or isinstance(b, str):
            return
        with self._lock:
            if a.alive:
                a.on_collision(b)
            if b.alive:
                b.on_collision(a)

    def destroy(self, e):
        self.entities.pop(e.name, None)
        if self.verbose:
            print(f"[world] {e.name} destroyed", flush=True)

    # ---- channels
    def channel(self, ch):
        self.channels.append(ch)
        ch.world = self
        return ch

    def send(self, sender, to=None, fields=None):
        for ch in self.channels:
            if ch.src != sender.name:
                continue
            if to and to not in (ch.dst, ch.id):
                continue
            payload = {f: sender.get(f, self.remote.get((sender.name, f))) for f in (fields or ch.fields)}
            ch.emit(payload)

    def deliver(self, ch, payload):
        """Called by transports when a message for channel ch arrives."""
        with self._lock:
            for k, v in payload.items():
                if k in ("channel", "from"):
                    continue
                if v is None:
                    continue
                self.remote[(ch.src, k)] = v
                self._latest[k] = v
            dst = self.entities.get(ch.dst)
            if dst is not None:
                for k, v in payload.items():
                    if k in ("channel", "from") or v is None:
                        continue
                    # own properties and fields this entity already mirrors are refreshed;
                    # a field never seen before becomes a mirrored attribute
                    if k in dst.props or k in dst._mirrored or not hasattr(dst, dst._attr(k)):
                        setattr(dst, dst._attr(k), v)
                        if k not in dst.props:
                            dst._mirrored.add(k)
                dst.on_message(ch.src, payload)

    # ---- main loop
    def run(self, seconds=None, ticks=None, dt=0.1):
        self.running = True
        for ch in self.channels:
            ch.start()
        for e in list(self.entities.values()):
            e._last = e._watch()
            e.on_start()
        n = 0
        t_end = time.monotonic() + seconds if seconds else None
        try:
            while self.running:
                now = time.monotonic()
                with self._lock:
                    for e in list(self.entities.values()):
                        if not e.alive:
                            continue
                        for t in e._timers:
                            if now >= t[1]:
                                t[1] = now + t[0] / 1000.0
                                t[2]()
                        if not e.alive:
                            continue
                        e.on_update(dt)
                        if not e.alive:
                            continue
                        cur = e._watch()
                        for k, v in cur.items():
                            if e._last.get(k) != v:
                                e.on_change(k)
                        e._last = cur
                for ch in self.channels:
                    ch.tick(now)
                n += 1
                if ticks and n >= ticks:
                    break
                if t_end and now >= t_end:
                    break
                time.sleep(dt)
        except KeyboardInterrupt:
            pass
        finally:
            self.running = False
            for ch in self.channels:
                ch.stop()


# ---------------------------------------------------------------- channels
class Channel:
    """Base transport.  src/dst are entity names; fields carried src -> dst."""
    def __init__(self, id, src, dst, fields, interval_ms=1000, local_src=False, local_dst=False, **cfg):
        self.id, self.src, self.dst, self.fields = id, src, dst, list(fields)
        self.interval = interval_ms / 1000.0
        self.local_src, self.local_dst = local_src, local_dst
        self.cfg = cfg
        self.world = None
        self._next = 0.0

    def start(self): pass
    def stop(self): pass

    def tick(self, now):
        # periodic auto-publish when the sender lives in this python process
        if self.local_src and now >= self._next:
            self._next = now + self.interval
            e = self.world.entities.get(self.src)
            if e is not None:
                # forward own value, else the latest value this process received for that field
                payload = {f: e.get(f) if e.get(f) is not None else self.world.latest(f)
                           for f in self.fields}
                if any(v is not None for v in payload.values()):
                    self.emit(payload)
        elif not self.local_src and self.world.simulate and now >= self._next:
            # simulation: invent plausible sensor data for the remote sender
            self._next = now + self.interval
            types, enums = self.cfg.get("types") or {}, self.cfg.get("enums") or {}
            self.receive({f: _fake(self.world, self.src, f, types.get(f), enums.get(f)) for f in self.fields})

    def publish(self, payload):
        raise NotImplementedError

    def emit(self, payload):
        """Publish; when both ends live in this process, also deliver directly
        (a python->python link must work without a hub/broker/serial loopback)."""
        self.publish(payload)
        if self.local_dst and self.local_src and not isinstance(self, LocalChannel):
            self.world.deliver(self, payload)

    def receive(self, payload):
        # enum fields (e.g. an FSM state) may arrive as their integer code: decode to the name
        for f, names in (self.cfg.get("enums") or {}).items():
            v = payload.get(f)
            if isinstance(v, (int, float)) and not isinstance(v, bool) and 0 <= int(v) < len(names):
                payload[f] = names[int(v)]
        self.world.deliver(self, payload)

    def envelope(self, payload):
        return dict({"channel": self.id, "from": self.src}, **payload)


def _fake(world, src, field, ftype=None, enum=None):
    prev = world.remote.get((src, field))
    base = {"temperature": 24.0, "humidity": 45.0, "distance": 100.0, "light": 300.0,
            "pressure": 1013.0, "voltage": 3.3}.get(field, 10.0)
    if enum:
        return random.choice(list(enum))
    if ftype == "bool" or isinstance(prev, bool):
        return random.random() < 0.5
    if ftype == "int":
        return int((prev if isinstance(prev, (int, float)) else base) + random.choice((-1, 0, 1)))
    if ftype == "string":
        return prev if isinstance(prev, str) else ""
    v = (prev if isinstance(prev, (int, float)) else base) + random.uniform(-1, 1)
    return round(v, 2)


class LocalChannel(Channel):
    def publish(self, payload):
        self.world.deliver(self, payload)
        if self.world.verbose:
            print(f"[{self.id}] {payload}", flush=True)


class HubChannel(Channel):
    """HTTP: POST/GET JSON on a NLCL hub (see Hub below)."""
    def __init__(self, *a, hub_url="http://localhost:8765", path=None, **kw):
        super().__init__(*a, **kw)
        self.url = hub_url.rstrip("/") + (path or f"/channel/{self.id}")
        self._seen = None
        self._poll_next = 0.0

    def publish(self, payload):
        if self.world.simulate and not self.cfg.get("force_net"):
            if self.world.verbose:
                print(f"[{self.id}] (simulated http) {payload}", flush=True)
            return
        data = json.dumps(self.envelope(payload)).encode()
        try:
            urllib.request.urlopen(urllib.request.Request(self.url, data, {"Content-Type": "application/json"}), timeout=2).read()
            if self.world.verbose:
                print(f"[{self.id}] -> hub {payload}", flush=True)
        except OSError as e:
            if self.world.verbose:
                print(f"[{self.id}] hub unreachable ({e}); payload {payload}", flush=True)

    def tick(self, now):
        super().tick(now)
        if not self.local_src and not self.world.simulate and now >= self._poll_next:
            self._poll_next = now + max(0.2, self.interval / 2)
            try:
                msg = json.loads(urllib.request.urlopen(self.url, timeout=2).read() or b"{}")
            except (OSError, ValueError):
                return
            stamp = msg.get("_t")
            if msg and stamp != self._seen:
                self._seen = stamp
                self.receive({k: v for k, v in msg.items() if not k.startswith("_")})


class SerialChannel(Channel):
    """Newline-delimited JSON over a serial port (pyserial).  Falls back to simulation."""
    def __init__(self, *a, baud=115200, port="auto", **kw):
        super().__init__(*a, **kw)
        self.baud, self.port, self.ser = baud, port, None

    def start(self):
        if self.world.simulate:
            return
        try:
            import serial
            import serial.tools.list_ports
        except ImportError:
            print(f"[{self.id}] pyserial not installed (pip install pyserial) -> simulating", flush=True)
            self.world.simulate = True
            return
        port = os.environ.get("NLCL_SERIAL_PORT") or (None if self.port == "auto" else self.port)
        if not port:
            ports = [p.device for p in serial.tools.list_ports.comports()]
            port = ports[0] if ports else None
        if not port:
            print(f"[{self.id}] no serial port found -> simulating", flush=True)
            self.world.simulate = True
            return
        self.ser = serial.Serial(port, self.baud, timeout=0.05)
        print(f"[{self.id}] serial {port} @ {self.baud}", flush=True)
        threading.Thread(target=self._reader, daemon=True).start()

    def _reader(self):
        buf = b""
        while self.world.running and self.ser:
            try:
                buf += self.ser.read(256)
            except Exception:
                break
            while b"\n" in buf:
                line, buf = buf.split(b"\n", 1)
                try:
                    msg = json.loads(line.decode("utf-8", "replace"))
                except ValueError:
                    continue
                if msg.get("channel", self.id) == self.id:
                    self.receive({k: v for k, v in msg.items() if k not in ("channel", "from")})

    def publish(self, payload):
        line = json.dumps(self.envelope(payload)) + "\n"
        if self.ser:
            self.ser.write(line.encode())
        elif self.world.verbose:
            print(f"[{self.id}] (serial) {line.strip()}", flush=True)

    def stop(self):
        if self.ser:
            self.ser.close()


class MqttChannel(Channel):
    def __init__(self, *a, broker="broker.hivemq.com", broker_port=1883, topic=None, **kw):
        super().__init__(*a, **kw)
        self.broker, self.bport, self.topic = broker, broker_port, topic or f"nlcl/{self.id}"
        self.client = None

    def start(self):
        if self.world.simulate:
            return
        try:
            import paho.mqtt.client as mqtt
        except ImportError:
            print(f"[{self.id}] paho-mqtt not installed (pip install paho-mqtt) -> simulating", flush=True)
            self.world.simulate = True
            return
        try:
            c = mqtt.Client(mqtt.CallbackAPIVersion.VERSION2) if hasattr(mqtt, "CallbackAPIVersion") else mqtt.Client()
            c.on_message = lambda cl, ud, m: self._on(m.payload)
            c.connect(self.broker, self.bport, 30)
            if not self.local_src:
                c.subscribe(self.topic)
            c.loop_start()
            self.client = c
            print(f"[{self.id}] mqtt {self.broker}:{self.bport} topic {self.topic}", flush=True)
        except OSError as e:
            print(f"[{self.id}] mqtt broker unreachable ({e}) -> simulating", flush=True)
            self.world.simulate = True

    def _on(self, raw):
        try:
            msg = json.loads(raw)
        except ValueError:
            return
        self.receive({k: v for k, v in msg.items() if k not in ("channel", "from")})

    def publish(self, payload):
        if self.client:
            self.client.publish(self.topic, json.dumps(self.envelope(payload)))
        elif self.world.verbose:
            print(f"[{self.id}] (mqtt {self.topic}) {payload}", flush=True)

    def stop(self):
        if self.client:
            self.client.loop_stop()


class UdpChannel(Channel):
    def __init__(self, *a, port=9876, host="127.0.0.1", **kw):
        super().__init__(*a, **kw)
        self.port, self.host, self.sock = port, host, None

    def start(self):
        if self.world.simulate:
            return
        self.sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        if not self.local_src:
            self.sock.bind(("0.0.0.0", self.port))
            self.sock.settimeout(0.2)
            threading.Thread(target=self._reader, daemon=True).start()

    def _reader(self):
        while self.world.running:
            try:
                data, _ = self.sock.recvfrom(4096)
                self.receive({k: v for k, v in json.loads(data).items() if k not in ("channel", "from")})
            except (socket.timeout, ValueError, OSError):
                continue

    def publish(self, payload):
        if self.sock:
            self.sock.sendto(json.dumps(self.envelope(payload)).encode(), (self.host, self.port))
        elif self.world.verbose:
            print(f"[{self.id}] (udp) {payload}", flush=True)


TRANSPORTS = {"local": LocalChannel, "http": HubChannel, "websocket": HubChannel, "serial": SerialChannel,
              "mqtt": MqttChannel, "udp": UdpChannel}


def make_channel(protocol, *a, **kw):
    return TRANSPORTS.get(protocol, LocalChannel)(*a, **kw)


# ---------------------------------------------------------------- hub
class Hub:
    """Tiny HTTP message hub + live dashboard.  GET/POST /channel/<id>, GET /state, GET /."""
    def __init__(self, port=8765):
        self.port = port
        self.data = {}
        self.server = None

    def start(self):
        hub = self

        class H(BaseHTTPRequestHandler):
            def log_message(self, *a):
                pass

            def _send(self, code, body, ctype="application/json"):
                b = body if isinstance(body, bytes) else body.encode()
                self.send_response(code)
                self.send_header("Content-Type", ctype)
                self.send_header("Access-Control-Allow-Origin", "*")
                self.send_header("Access-Control-Allow-Headers", "Content-Type")
                self.send_header("Access-Control-Allow-Methods", "GET, POST, OPTIONS")
                self.send_header("Access-Control-Allow-Private-Network", "true")
                self.send_header("Content-Length", str(len(b)))
                self.end_headers()
                self.wfile.write(b)

            def do_OPTIONS(self):
                self._send(204, b"")

            def do_GET(self):
                if self.path.startswith("/channel/"):
                    self._send(200, json.dumps(hub.data.get(self.path.split("/", 2)[2], {})))
                elif self.path == "/state":
                    self._send(200, json.dumps(hub.data))
                else:
                    self._send(200, DASHBOARD_HTML, "text/html; charset=utf-8")

            def do_POST(self):
                if not self.path.startswith("/channel/"):
                    return self._send(404, "{}")
                n = int(self.headers.get("Content-Length") or 0)
                try:
                    msg = json.loads(self.rfile.read(n) or b"{}")
                except ValueError:
                    return self._send(400, '{"error":"bad json"}')
                msg["_t"] = time.time()
                hub.data[self.path.split("/", 2)[2]] = msg
                self._send(200, '{"ok":true}')

        try:
            self.server = ThreadingHTTPServer(("0.0.0.0", self.port), H)
        except OSError as e:
            print(f"[hub] port {self.port} busy ({e}); assuming another hub is running", flush=True)
            return False
        threading.Thread(target=self.server.serve_forever, daemon=True).start()
        print(f"[hub] http://localhost:{self.port}  (live dashboard)", flush=True)
        return True

    def stop(self):
        if self.server:
            self.server.shutdown()


